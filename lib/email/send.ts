import { SITE_URL, TOOL_NAME } from "../site/brand";

/**
 * Emailing a finished report, through Resend.
 *
 * Called with fetch rather than the Resend SDK: it is one POST, and the SDK
 * would be a dependency for the sake of a URL and a header.
 *
 * Every failure is a typed EmailError whose message and hint the visitor sees.
 * There is no fallback that pretends a message went out - a report someone is
 * waiting for in their inbox is exactly where a silent failure hurts most.
 */

export type EmailErrorCode =
  | "not_configured"
  | "invalid_address"
  | "invalid_attachment"
  | "rejected"
  | "rate_limited"
  | "unavailable"
  | "network";

export class EmailError extends Error {
  constructor(
    readonly code: EmailErrorCode,
    message: string,
    readonly hint: string,
    readonly retryable = false,
    /** HTTP status for the route to return. */
    readonly status = 502,
  ) {
    super(message);
    this.name = "EmailError";
  }

  toJSON() {
    return {
      code: this.code,
      message: this.message,
      hint: this.hint,
      retryable: this.retryable,
    };
  }
}

const FALLBACK = "The PDF can still be downloaded from the button above.";

export interface EmailConfig {
  apiKey: string;
  /** e.g. "CertifyMe.net <reports@certifyme.net>", on a domain verified in Resend. */
  from: string;
  replyTo?: string;
}

/** Both settings are needed; either missing means the feature is off. */
export function emailConfig(): EmailConfig | null {
  const apiKey = process.env.RESEND_API_KEY?.trim();
  const from = process.env.EMAIL_FROM?.trim();
  if (!apiKey || !from) return null;
  const replyTo = process.env.EMAIL_REPLY_TO?.trim() || undefined;
  return { apiKey, from, replyTo };
}

export const notConfigured = () =>
  new EmailError(
    "not_configured",
    "Emailing reports is not set up on this deployment.",
    `${FALLBACK} To switch it on, set RESEND_API_KEY and EMAIL_FROM on the server.`,
    false,
    503,
  );

/** Deliberately loose: the provider is the real validator, this stops typos. */
const ADDRESS = /^[^\s@,;<>]+@[^\s@,;<>]+\.[^\s@,;<>]+$/;

export function validateAddress(raw: unknown): string {
  const address = typeof raw === "string" ? raw.trim() : "";
  if (address.length === 0 || address.length > 254 || !ADDRESS.test(address)) {
    throw new EmailError(
      "invalid_address",
      "That does not look like an email address.",
      "Check it for typos and try again.",
      false,
      400,
    );
  }
  return address;
}

export const MAX_ATTACHMENT_BYTES = 3 * 1024 * 1024;

/**
 * Only a report this tool rendered is accepted.
 *
 * Without this the route would email any file to any address, which is a free
 * spam relay with our domain's name on it. react-pdf writes its own name as
 * Producer and our tool name as Creator in plain bytes. Both can be forged, so
 * this raises the cost of abuse rather than ending it, alongside the rate
 * limits - but it does mean nothing arbitrary goes out with a fixed message.
 */
export function validateReport(bytes: Uint8Array): void {
  const invalid = (message: string) =>
    new EmailError("invalid_attachment", message, FALLBACK, false, 400);

  if (bytes.byteLength === 0) throw invalid("The report was empty.");
  if (bytes.byteLength > MAX_ATTACHMENT_BYTES) {
    throw invalid("The report is too large to email.");
  }
  const text = new TextDecoder("latin1").decode(bytes);
  if (
    !text.startsWith("%PDF-") ||
    !text.includes("(react-pdf)") ||
    !text.includes(`(${TOOL_NAME})`)
  ) {
    throw invalid("Only reports generated by this tool can be emailed.");
  }
}

/** Keeps a predictable, header-safe attachment name whatever the client sent. */
export function safeFilename(raw: unknown): string {
  const stem = (typeof raw === "string" ? raw : "")
    .replace(/\.pdf$/i, "")
    .replace(/[^a-zA-Z0-9_-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
  return `${stem || "emod-analysis"}.pdf`;
}

const SUBJECT = "Your experience mod analysis";

function body(): { text: string; html: string } {
  const lines = [
    `Attached is the experience mod analysis you generated with ${TOOL_NAME}.`,
    "The figures are calculated from the worksheet you supplied, and any suggestions in it are worth confirming with your agent, broker or carrier.",
    `You can run it again on any NCCI experience rating worksheet at ${SITE_URL}.`,
    "This is a one-off message sent because this address was entered in the tool. Your address was used only to send it.",
  ];
  return {
    text: lines.join("\n\n"),
    html: lines.map((l) => `<p>${l}</p>`).join(""),
  };
}

/**
 * Sends the report. The address and the PDF are passed straight through and
 * never logged or kept; a failure says what happened without echoing either.
 */
export async function sendReport(
  config: EmailConfig,
  to: string,
  filename: string,
  pdf: Uint8Array,
): Promise<void> {
  let response: Response;
  try {
    response = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: {
        authorization: `Bearer ${config.apiKey}`,
        "content-type": "application/json",
      },
      body: JSON.stringify({
        from: config.from,
        to: [to],
        ...(config.replyTo ? { reply_to: config.replyTo } : {}),
        subject: SUBJECT,
        ...body(),
        attachments: [
          { filename, content: Buffer.from(pdf).toString("base64") },
        ],
      }),
    });
  } catch {
    throw new EmailError(
      "network",
      "The email service could not be reached.",
      `Trying again in a moment may work. ${FALLBACK}`,
      true,
    );
  }

  if (response.ok) return;

  // Resend's message is about our configuration (an unverified sending domain,
  // a revoked key), never about the visitor, so it is safe to pass on and is
  // what whoever runs the deployment needs to see.
  let detail = "";
  try {
    const parsed = (await response.json()) as { message?: unknown };
    if (typeof parsed.message === "string") detail = parsed.message.slice(0, 200);
  } catch {
    // No usable body; the status alone decides the message.
  }

  if (response.status === 429) {
    throw new EmailError(
      "rate_limited",
      "The email service is busy right now.",
      `Trying again in a minute should work. ${FALLBACK}`,
      true,
      429,
    );
  }
  if (response.status >= 500) {
    throw new EmailError(
      "unavailable",
      "The email service is having problems.",
      `Trying again later may work. ${FALLBACK}`,
      true,
      503,
    );
  }
  // Only 401 means the key itself is wrong. Resend also answers 403 to a
  // valid key in test mode (no verified domain) for any recipient other than
  // the account owner, and its message says exactly that - so a 403 falls
  // through to the general case, which passes the message on.
  if (response.status === 401) {
    throw new EmailError(
      "rejected",
      "The email service refused this deployment's credentials.",
      `${FALLBACK}${detail ? ` (${detail})` : ""}`,
    );
  }
  throw new EmailError(
    "rejected",
    "The email service would not send this message.",
    `${FALLBACK}${detail ? ` (${detail})` : ""}`,
  );
}
